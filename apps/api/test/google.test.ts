import { test } from "node:test";
import { asUser, TEST_USER } from "./helpers.js";
import assert from "node:assert/strict";
import { mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { DEFAULT_BOT, DEFAULT_SETTINGS, type VoiceSessionConfig } from "@rex/shared";

test("Google embeddings use separate keys and spaces; Live tokens, tools and transcripts have a bounded lifecycle", async () => {
  const directory = mkdtempSync(path.join(tmpdir(), "rex-google-test-"));
  process.env.REX_DATA_DIR = directory;
  const { db } = await import("../src/db.js");
  const { createConversation, listMessages } = await import("../src/conversations.js");
  const { voiceRoutes } = await import("../src/routes/voice.js");
  const { embedTexts } = await import("../src/llm.js");
  const { retrieveMemories } = await import("../src/memory/store.js");
  const { activeChats } = await import("../src/groups.js");
  const settings = { ...DEFAULT_SETTINGS, llmApiKey: "different-chat-key", googleApiKey: "google-test-key" };
  const requests: Array<{ url: string; body: any; headers: Headers }> = [];
  const fetchOriginal = globalThis.fetch;
  let rejectGoogle = false;
  globalThis.fetch = async (input, init) => {
    const url = String(input);
    assert.ok(url.startsWith("https://generativelanguage.googleapis.com/"));
    const body = JSON.parse(String(init?.body));
    const headers = new Headers(init?.headers);
    requests.push({ url, body, headers });
    assert.equal(headers.get("x-goog-api-key"), "google-test-key");
    assert.equal(headers.has("Authorization"), false);
    if (rejectGoogle) return Response.json({ error: "quota" }, { status: 429 });
    if (url.endsWith(":embedContent")) return Response.json({ embedding: { values: Array(768).fill(body.content.parts[0].text.includes("query:") ? .5 : 1) } });
    return Response.json({ name: "auth_tokens/test-token" });
  };
  const post = (url: string, body: unknown) => asUser(voiceRoutes).request(url, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(body) });
  let sessionId: string | undefined;
  try {
    assert.equal(await embedTexts({ ...settings, googleApiKey: "" }, ["Text"]), null);
    const vectors = await embedTexts(settings, ["First", "Second"]);
    assert.equal(vectors?.length, 2);
    assert.equal(requests.filter((request) => request.url.endsWith(":embedContent")).length, 2);
    assert.equal(requests[0]!.body.model, "models/gemini-embedding-2");
    assert.equal(requests[0]!.body.outputDimensionality, 768);
    db.prepare("INSERT INTO memories (id, content, embedding, embedding_space, created_at, updated_at, user_id) VALUES (?, ?, ?, ?, ?, ?, ?)").run("old", "An old preference", "[0.1,0.2]", "different-model", "2026-01-01", "2026-01-01", TEST_USER.id);
    const memories = await retrieveMemories(settings, TEST_USER.id, "What matters?");
    assert.equal(memories[0]?.id, "old");
    assert.equal((db.prepare("SELECT embedding_space FROM memories WHERE id = 'old'").get() as { embedding_space: string }).embedding_space, "google:gemini-embedding-2:768");
    const bot = createConversation("Voice test", { ...DEFAULT_BOT, name: "Voice test" }, TEST_USER.id);
    assert.equal((await post("/voice", { conversationId: bot.id, settings: DEFAULT_SETTINGS })).status, 400);
    assert.equal((await post("/voice", { conversationId: "missing", settings })).status, 400);
    const started = await post("/voice", { conversationId: bot.id, settings });
    assert.equal(started.status, 200);
    const config = await started.json() as VoiceSessionConfig;
    sessionId = config.id;
    assert.ok(config.url.includes("access_token=auth_tokens%2Ftest-token"));
    assert.ok(!JSON.stringify(config).includes("google-test-key"));
    assert.equal(config.setup.model, "models/gemini-3.8-live");
    assert.equal((config.setup.generationConfig as { speechConfig?: { voiceConfig?: { prebuiltVoiceConfig?: { voiceName?: string } } } }).speechConfig?.voiceConfig?.prebuiltVoiceConfig?.voiceName, "Kore");
    assert.ok(JSON.stringify(config.setup).includes("end_call"));
    assert.ok(JSON.stringify(config.setup).includes("R-38"));
    const auth = requests.find((request) => request.url.endsWith("/auth_tokens"))!;
    assert.equal(auth.body.uses, 1);
    assert.deepEqual(auth.body.bidiGenerateContentSetup, config.setup);
    assert.ok(activeChats.has(bot.id));
    assert.equal((await post("/voice", { conversationId: bot.id, settings })).status, 409);
    assert.equal((await post(`/voice/${config.id}/tool`, { name: "react_message", args: {} })).status, 400);
    const hangup = await post(`/voice/${config.id}/tool`, { name: "end_call", args: { reason: "User said goodbye" } });
    assert.equal(hangup.status, 200);
    assert.deepEqual(await hangup.json(), { output: "Ending the call: User said goodbye", endCall: true });
    const tool = await post(`/voice/${config.id}/tool`, { name: "web_search", args: { query: "test" } });
    assert.match((await tool.json() as { output: string }).output, /unavailable/);
    const turn = { id: "turn-1", user: "Hello voice", assistant: "Hello from Google Live" };
    assert.equal((await post(`/voice/${config.id}/turn`, turn)).status, 200);
    assert.equal((await post(`/voice/${config.id}/turn`, turn)).status, 200);
    assert.equal(listMessages(bot.id).filter((message) => message.role === "user").length, 1);
    assert.deepEqual(listMessages(bot.id).map((message) => message.role), ["user", "tool", "assistant"]);
    assert.equal(listMessages(bot.id).find((message) => message.role === "assistant")?.botName, "Voice test");
    await asUser(voiceRoutes).request(`/voice/${config.id}`, { method: "DELETE" });
    assert.equal(activeChats.has(bot.id), false);
    assert.equal((await post(`/voice/${config.id}/turn`, turn)).status, 410);
    rejectGoogle = true;
    assert.equal((await post("/voice", { conversationId: bot.id, settings })).status, 502);
    assert.equal(activeChats.has(bot.id), false);
    assert.equal(await embedTexts(settings, ["Text"]), null);
  } finally {
    if (sessionId) await asUser(voiceRoutes).request(`/voice/${sessionId}`, { method: "DELETE" });
    globalThis.fetch = fetchOriginal;
    db.close();
    rmSync(directory, { recursive: true, force: true });
  }
});
