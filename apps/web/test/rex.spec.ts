let model: Server;
let modelUrl: string;
const modelPrompts: string[] = [];
test.beforeAll(async () => {
  model = createServer(async (request, response) => {
    let raw = "";
    for await (const chunk of request) raw += chunk;
    const body = JSON.parse(raw);
    if (!body.stream) {
      response.setHeader("Content-Type", "application/json");
      response.end(JSON.stringify({ choices: [{ message: { content: '["Uses a disposable workspace in this test."]' } }] }));
      return;
    }
    const messages = body.messages as Array<{ role: string; content: string }>;
    modelPrompts.push(messages.find((message) => message.role === "system")?.content ?? "");
    const hasTools = messages.some((message) => message.role === "tool");
    const standaloneReply = messages.some((message) => message.role === "user" && message.content.includes("image/png")) ? "Image attachments received." : messages.some((message) => message.role === "user" && message.content === "Hello") ? "Hello from your configured bot." : undefined;
    response.setHeader("Content-Type", "text/event-stream");
    const delta = standaloneReply ? { content: standaloneReply } : hasTools ? { content: "Python calculated 42 inside Rex Computer." } : {
      content: "I'll calculate it in my workspace.",
      tool_calls: [
        { index: 0, id: "react-test", type: "function", function: { name: "react_message", arguments: JSON.stringify({ emoji: "🔥" }) } },
        { index: 1, id: "exec-test", type: "function", function: { name: "computer_exec", arguments: JSON.stringify({ command: "python -c 'print(6 * 7)'" }) } },
      ],
    };
    response.end(`data: ${JSON.stringify({ choices: [{ delta }] })}\n\ndata: [DONE]\n\n`);
  });
  await new Promise<void>((resolve) => model.listen(0, "127.0.0.1", resolve));
  modelUrl = `http://127.0.0.1:${(model.address() as AddressInfo).port}`;
});
test.afterAll(async () => { await new Promise<void>((resolve) => model.close(() => resolve())); });
test.beforeEach(async ({ request }) => { await request.post("http://127.0.0.1:18787/computer/stop", { data: {} }); });
test.afterEach(async ({ request }) => { await request.post("http://127.0.0.1:18787/computer/stop", { data: {} }); });

